 /* ============================================================
   KPI CALCULATIONS v2.1
============================================================ */

function calculateKPIs(data){


    let totalTasks = 0;

    let completedTasks = 0;



    const rooms = new Set();

    const staff = new Set();




    data.forEach(record=>{


        if(record.room){

            rooms.add(record.room);

        }




        if(record.staff){


            String(record.staff)

            .split(",")

            .map(name=>name.trim())

            .filter(Boolean)

            .forEach(name=>{

                staff.add(name);

            });


        }





        Object.values(

            record.tasks_completed || {}

        )

        .forEach(task=>{


            totalTasks++;



            if(task === "Y"){

                completedTasks++;

            }



        });



    });





    const compliance =

        totalTasks

        ?

        Math.round(

            (completedTasks / totalTasks) * 100

        )

        :

        0;





    return {


        totalSurveys:

            data.length,


        totalRooms:

            rooms.size,


        totalStaff:

            staff.size,


        totalTasks,


        completedTasks,


        compliance,


        status:

            getComplianceStatus(compliance)



    };


}






