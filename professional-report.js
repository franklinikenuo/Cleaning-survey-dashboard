/* ============================================================
   ROOM STATISTICS
============================================================ */

function getRoomStatistics(data){


    const rooms = {};




    data.forEach(record=>{


        if(!record.room)

            return;




        if(!rooms[record.room]){


            rooms[record.room] = {


                room:

                    record.room,


                surveys:

                    0,


                yes:

                    0,


                total:

                    0



            };


        }




        rooms[record.room].surveys++;





        Object.values(

            record.tasks_completed || {}

        )

        .forEach(task=>{


            rooms[record.room].total++;




            if(task==="Y"){

                rooms[record.room].yes++;

            }



        });




    });





    return Object.values(rooms)

    .map(room=>({


        ...room,


        compliance:


            room.total

            ?

            Math.round(

                (room.yes / room.total) * 100

            )

            :

            0



    }))


    .sort(

        (a,b)=>

            b.compliance-a.compliance

    );


}






/* ============================================================
   LOWEST PERFORMING ROOMS
============================================================ */

function getLowestPerformingRooms(data){


    return getRoomStatistics(data)

    .slice()

    .sort(

        (a,b)=>

            a.compliance-b.compliance

    )

    .slice(0,5);


}
